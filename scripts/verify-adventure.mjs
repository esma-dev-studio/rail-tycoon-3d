import assert from 'node:assert/strict';
import { createServer } from 'vite';

const memory = new Map([['rt3d-muted', '1']]);
const listeners = new Map();
globalThis.window = {
  localStorage: { getItem: (k) => memory.get(k) ?? null, setItem: (k,v) => memory.set(k,v), removeItem: (k) => memory.delete(k) },
  addEventListener: (name, fn) => listeners.set(name, fn),
};
globalThis.document = { hidden: false, addEventListener() {} };
const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { useGameStore: store, flushSave } = await server.ssrLoadModule('/src/store/gameStore.ts');
  const { sim } = await server.ssrLoadModule('/src/sim/simInstance.ts');
  const { stepTrains, spawnPassengers, createSim, addTrainRuntime } = await server.ssrLoadModule('/src/sim/simulation.ts');
  const { TOWNS, ALL_TOWNS } = await server.ssrLoadModule('/src/data/world.ts');
  const { TOWN_PROJECTS, projectVisitors, townAttraction } = await server.ssrLoadModule('/src/data/development.ts');
  const { MISSIONS } = await server.ssrLoadModule('/src/data/missions.ts');
  const s = () => store.getState();
  const route = (a,b) => { s().setBuildMode('route'); s().townClick(a); s().townClick(b); s().confirmEasyRoute(); };
  s().reset();
  assert.equal(s().towns.length, 5);
  s().buyDecoration('flower-garden');
  assert.equal(s().money,10000,'the first railway budget cannot be spent on decorations');
  store.setState({money:0});
  s().claimStarterGrant();
  assert.equal(s().money,10000,'a legacy town with no railway can start again');
  s().townClick('t_forest');
  assert.equal(s().selection, null);
  store.setState({ routeStartTown: 't_midori', routeEndTown: 't_forest' });
  s().confirmEasyRoute();
  assert.equal(s().lines.length, 0, 'locked destinations cannot be built through direct calls');
  route('t_midori', 't_chuo');
  assert.equal(s().lines.length, 1);
  const afterBuild = s().money;
  route('t_chuo', 't_midori');
  assert.equal(s().lines.length, 1);
  assert.equal(s().money, afterBuild, 'duplicate routes are not charged');
  for (let i=0;i<2000;i++) stepTrains(sim,.05,s().lines,(fare,town,p) => s().deliver(fare,town,p));
  assert.equal(s().totalDelivered,6,'both directions deliver the initial 3 passengers exactly once');
  assert.equal(s().townProgress.t_midori.delivered,3);
  assert.equal(s().townProgress.t_chuo.delivered,3);
  s().completeMission(0);
  const afterMission = s().money;
  s().completeMission(0);
  assert.equal(s().money,afterMission,'mission reward cannot be claimed twice');
  const p = TOWN_PROJECTS[0];
  s().startProject(p.id);
  const paid = s().money;
  s().startProject(p.id);
  assert.equal(s().money,paid,'project construction is charged once');
  assert.equal(projectVisitors(p,s().projects[p.id],s().townProgress[p.townId].delivered),0,'old arrivals do not build a new project');
  assert.equal(townAttraction(p.townId,s().projects),4);
  const beforeInviteMoney=s().money;
  const beforeInviteDelivered=s().totalDelivered;
  s().inviteVisitors('t_midori');
  const pendingInvites=()=>[...sim.waiting.values()].flat().filter(p=>p.toTownId==='t_midori').length;
  assert.equal(pendingInvites(),6,'invited visitors really wait at another station');
  s().inviteVisitors('t_midori');
  assert.equal(pendingInvites(),6,'repeated taps cannot flood the station');
  assert.equal(s().money,beforeInviteMoney,'invitations are free');
  assert.equal(s().totalDelivered,beforeInviteDelivered,'invitations do not grant arrivals or revenue');
  s().completeProject(p.id);
  assert.equal(s().projects[p.id].completed,false);
  for(let i=0;i<p.visitors;i++)s().deliver(100,p.townId);
  s().completeProject(p.id);
  assert.equal(s().projects[p.id].completed,true);
  assert.equal(s().towns.length,6);
  assert.equal(townAttraction(p.townId,s().projects),2);
  const rewarded = s().money;
  s().completeProject(p.id);
  assert.equal(s().money,rewarded,'project completion cannot pay twice');
  assert.equal(s().towns.filter(t=>t.id==='t_forest').length,1);
  store.setState({ money: 100000 });
  for(const p of TOWN_PROJECTS.slice(1,5)){
    if(!s().lines.some(l=>l.stations.includes(p.townId)))route('t_chuo',p.townId);
    s().startProject(p.id);
    for(let i=0;i<p.visitors;i++)s().deliver(100,p.townId);
    s().completeProject(p.id);
    const expected={p_library:6,p_market:7,p_music:7,p_aquarium:8}[p.id];
    assert.equal(s().towns.length,expected,'tourist towns unlock in order');
  }
  route('t_chuo','t_forest');
  assert.ok(s().lines.at(-1).stations.includes('t_forest'));
  const id=s().lines[0].id;
  s().upgradeLineCapacity(id);
  assert.equal(s().lines[0].capacityLevel,1,'upgrades wait for the first chapter');
  store.setState({ missionIndex:6, gameCleared:false,money:100000 });
  s().upgradeLineCapacity(id);
  assert.equal(sim.trains.get(s().trainDefs[0].id).capacity,30);
  s().upgradeLineSpeed(id);
  assert.equal(s().lines[0].speedLevel,2);
  const ghost=createSim();
  spawnPassengers(ghost,30,[{id:'ghost',stations:['t_midori','t_forest'],pathNodes:[]}],()=>.5,TOWNS);
  assert.equal([...ghost.waiting.values()].flat().length,0,'no passengers spawn for a locked destination');
  const transferSim=createSim();
  const transferLines=[s().lines[0],s().lines.find(l=>l.stations.includes('t_chuo')&&l.stations.includes('t_minato'))];
  transferLines.forEach((line,i)=>addTrainRuntime(transferSim,'test'+i,line.id,line.pathNodes,line.stations,line.color,true));
  transferSim.waiting.get('t_midori').push({id:9001,fromTownId:'t_midori',toTownId:'t_minato',transfers:0});
  transferSim.waiting.get('t_minato').push({id:9002,fromTownId:'t_minato',toTownId:'t_midori',transfers:0});
  const deliveredTransfers=[];
  for(let i=0;i<3000;i++)stepTrains(transferSim,.05,transferLines,(fare,town,p)=>deliveredTransfers.push({town,transfers:p.transfers,id:p.id,fare}));
  assert.equal(deliveredTransfers.length,2,'both directions transfer and deliver exactly once');
  assert.ok(deliveredTransfers.every(p=>p.transfers===1&&p.fare>0));
  assert.equal(deliveredTransfers.find(p=>p.id===9001).town,'t_minato');
  assert.equal(deliveredTransfers.find(p=>p.id===9002).town,'t_midori');
  assert.deepEqual(MISSIONS[5].progress({...s(),towns:TOWNS}),[5,5],'extra towns do not move the original goal');
  // Saving must use the latest state, including an operation immediately before pagehide.
  store.setState({ money:12345 });
  listeners.get('pagehide')();
  let saved=JSON.parse(memory.get('rail-tycoon-3d-save-v2'));
  assert.equal(saved.adventureVersion,7);
  assert.equal(saved.money,12345);
  assert.equal(saved.projects.p_park.completed,true);
  assert.equal(saved.lines[0].capacityLevel,2);
  const baseline=s().townProgress[ALL_TOWNS[0].id].delivered;
  store.setState({missionIndex:MISSIONS.length,tourNumber:0,tourStartedAt:baseline});
  for(let i=0;i<12;i++)s().deliver(100,ALL_TOWNS[0].id);
  s().claimTour();
  const tourReward=s().money;
  s().claimTour();
  assert.equal(s().money,tourReward);
  assert.equal(s().tourNumber,1);
  flushSave();
  await server.close();
  const reload=await createServer({configFile:false,server:{middlewareMode:true},appType:'custom'});
  const restored=await reload.ssrLoadModule('/src/store/gameStore.ts');
  assert.equal(restored.useGameStore.getState().towns.length,8);
  assert.equal(restored.useGameStore.getState().projects.p_park.completed,true);
  assert.equal(restored.useGameStore.getState().tourNumber,1);
  restored.flushSave();
  await reload.close();
  // V6 saves have no projects and must remain usable.
  saved={...saved,adventureVersion:6,projects:undefined,tourNumber:undefined,tourStartedAt:undefined};
  memory.set('rail-tycoon-3d-save-v2',JSON.stringify(saved));
  const legacy=await createServer({configFile:false,server:{middlewareMode:true},appType:'custom'});
  const migrated=await legacy.ssrLoadModule('/src/store/gameStore.ts');
  assert.equal(migrated.useGameStore.getState().towns.length,5);
  assert.equal(migrated.useGameStore.getState().money,12345);
  assert.equal(migrated.useGameStore.getState().lines[0].capacityLevel,2);
  assert.deepEqual(migrated.useGameStore.getState().projects,{});
  await legacy.close();
  console.log('adventure verification passed: round trips, duplicate guards, 8 towns, construction, rewards, upgrades, tours, fresh saves and V6 migration');
} finally { await server.close(); }
